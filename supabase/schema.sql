-- Run this entire script once in Supabase: SQL Editor -> New query -> Run.
-- The Flask server uses the private SUPABASE_KEY only; never expose it in browser code.

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.results (
  id bigint generated by default as identity primary key,
  event text not null,
  winner text not null,
  position text not null,
  details text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  filename text not null,
  caption text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.passes (
  id bigint generated by default as identity primary key,
  token text unique not null,
  participant text not null,
  school text not null,
  event text not null,
  official_ref text not null,
  created_at timestamptz not null default now()
);

-- Keep browser/anonymous access disabled. The server's private secret key bypasses RLS.
alter table public.announcements enable row level security;
alter table public.results enable row level security;
alter table public.gallery enable row level security;
alter table public.passes enable row level security;

-- Create the public-read image bucket. Uploads and deletes are performed only by the server.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('technova-gallery', 'technova-gallery', true, 8388608, array['image/webp'])
on conflict (id) do update
set public = true,
    file_size_limit = 8388608,
    allowed_mime_types = array['image/webp'];


-- Single-row public homepage settings. Writes are performed only by the authenticated Flask admin.
create table if not exists public.site_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.site_settings enable row level security;
